// 辞書オブジェクトの省略記法『{A}』の回帰テスト。
// 回帰: 省略記法の値が getVarNameRef を通らず、グローバル変数 A が
// main__A に解決されずに undefined になっていた。
func TestDictShorthandVariableReference(t *testing.T) {
	tests := []struct{ name, code, want string }{
		{
			"トップレベルのグローバル変数",
			"A = 10\nD = {A}\nD[\"A\"]を表示",
			"10",
		},
		{
			"関数内からのグローバル変数",
			"A = 10\n●hogeとは\n  D = {A}\n  D[\"A\"]を表示\nここまで\nhoge()",
			"10",
		},
		{
			"関数内のローカル変数",
			"●hogeとは\n  B = 20\n  E = {B}\n  E[\"B\"]を表示\nここまで\nhoge()",
			"20",
		},
		{
			"同名グローバル変数を隠すローカル変数",
			"A = 10\n●hogeとは\n  変数 A = 20\n  D = {A}\n  D[\"A\"]を表示\nここまで\nhoge()\nAを表示",
			"20\n10",
		},
		{
			"関数の引数",
			"●hoge(V)とは\n  D = {V}\n  D[\"V\"]を表示\nここまで\nhoge(30)",
			"30",
		},
		{
			"複数の省略キーと明示キーの混在",
			"A = 1\nB = 2\nD = {A, B, \"C\": 3}\nD[\"A\"]を表示\nD[\"B\"]を表示\nD[\"C\"]を表示",
			"1\n2\n3",
		},
		{
			"未定義変数は通常参照と同じ",
			"D = {Z}\nD[\"Z\"]を表示\nZを表示",
			"undefined\nundefined",
		},
		{
			"文字列リテラルの省略",
			"D = {\"A\"}\nD[\"A\"]を表示",
			"A",
		},
		{
			"数値リテラルの省略",
			"D = {1}\nD[1]を表示",
			"1",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := run(t, tt.code); got != tt.want {
				t.Errorf("%q = %q, want %q", tt.code, got, tt.want)
			}
		})
	}
}

// 本家 Issue #2686 で決まった仕様に gonako を合わせるためのテスト (#518)。
// {1:10} は {"1":10}、{A} は {"A":A}、{10} は {"10":10}。
// トップレベルと関数内で解釈が変わらないこと、そして添字の中など
// パーサーが巻き戻して読み直す位置でも結果が変わらないことを固定する。
func TestDictShorthandAlignment518(t *testing.T) {
	tests := []struct{ name, code, want string }{
		// 数値キー (トップレベル)
		{"数値キー", "{1:10}をJSON変換して表示", `{"1":10}`},
		{"数値キー 0", "{0:10}をJSON変換して表示", `{"0":10}`},
		{"数値キー 小数", "{1.5:10}をJSON変換して表示", `{"1.5":10}`},
		{"数値キー 16進数", "{0xFF:1}をJSON変換して表示", `{"255":1}`},
		{"数値キー 複数", "{1:10,2:20}をJSON変換して表示", `{"1":10,"2":20}`},
		{"数値キー 値が式", "A=5\n{1:A+1}をJSON変換して表示", `{"1":6}`},
		// 数値キー (関数内でも同じ)
		{"数値キー 関数内", "●テストとは\n{1:10}をJSON変換して戻る\nここまで\nテストを表示", `{"1":10}`},
		{"数値キー 関数内 値が式", "A=5\n●テストとは\n{1:A+1}をJSON変換して戻る\nここまで\nテストを表示", `{"1":6}`},
		// 数値のみ (関数内でも同じ)
		{"数値のみ", "{10}をJSON変換して表示", `{"10":10}`},
		{"数値のみ 関数内", "●テストとは\n{10}をJSON変換して戻る\nここまで\nテストを表示", `{"10":10}`},
		// 組み合わせ (トップレベルと関数内)
		{"組み合わせ", "A=1\n{1:10,A,10}をJSON変換して表示", `{"1":10,"10":10,"A":1}`},
		{"組み合わせ 関数内", "A=1\n●テストとは\n{1:10,A,10}をJSON変換して戻る\nここまで\nテストを表示", `{"1":10,"10":10,"A":1}`},
		// 入れ子
		{"入れ子 数値キーの中に省略記法", "A=5\n{1:{A}}をJSON変換して表示", `{"1":{"A":5}}`},
		{"入れ子 省略記法の中に数値キー", "A=5\n{A:{1:2}}をJSON変換して表示", `{"A":{"1":2}}`},
		// 巻き戻し後の再パースでも結果が変わらない (添字の中)
		{"添字の中の省略記法", "A=1;B=[100,200];B[({A}$A)-1]を表示", "100"},
		{"添字の中の明示形 (対照)", "A=1;B=[100,200];B[({A:A}$A)-1]を表示", "100"},
		{"添字の中の数値キー (対照)", "B=[100,200];B[({1:1}$1)-1]を表示", "100"},
		{"添字の中の省略記法 関数内", "A=1\n●テストとは\nB=[100,200]\nB[({A}$A)-1]を戻る\nここまで\nテストを表示", "100"},
		{"添字の中の文字列省略記法 (対照)", "B=[100,200];B[(({\"A\"}$\"A\")の文字数)-1]を表示", "100"},
		// 関数より後で定義される大域変数 (後処理で解決される経路)
		{"関数内 後で定義される大域変数", "●テストとは\n{A}をJSON変換して戻る\nここまで\nA=1\nテストを表示", `{"A":1}`},
		{"関数内 後で定義される大域変数 添字の中", "●テストとは\nB=[100,200]\nB[({A}$A)-1]を戻る\nここまで\nA=1\nテストを表示", "100"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := run(t, tt.code); got != tt.want {
				t.Errorf("%q = %q, want %q", tt.code, got, tt.want)
			}
		})
	}
}

// 数値キーの書き間違いは文法エラーになること (#518)。
// 別の原因の文法エラーで通ってしまわないよう、文面まで確かめる。
func TestDictShorthandNumberKeyErrors518(t *testing.T) {
	tests := []struct{ code, wantErr string }{
		{"{1:}をJSON変換して表示", "辞書オブジェクトの宣言で値がありません。"},
		{"{1:10:20}をJSON変換して表示", "辞書オブジェクトの宣言で末尾の『}』がありません。"},
	}
	for _, tt := range tests {
		if _, err := vm.RunSource(tt.code, "main.nako3", nil); err == nil {
			t.Errorf("%q: エラーになりませんでした", tt.code)
		} else if !strings.Contains(err.Error(), tt.wantErr) {
			t.Errorf("%q: エラー %v に %q が含まれません", tt.code, err, tt.wantErr)
		}
	}
}
