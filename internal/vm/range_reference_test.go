package vm_test

import "testing"

// #342: 範囲辞書での『参照』は本家と同じ結果を返し、panic しない。
// 文字列は substring、配列は slice の規約 (末尾は含む指定)。
func TestRangeReferenceFromSource(t *testing.T) {
	tests := []struct{ name, code, want string }{
		{"負の末尾(文字列)", `「abc」から{「先頭」:0,「末尾」:-2}を参照して表示`, ""},
		{"逆転(文字列)", `「abc」から{「先頭」:2,「末尾」:0}を参照して表示`, "b"},
		{"逆転(配列)", `A=[0,1,2,3];(Aから{「先頭」:2,「末尾」:0}を参照)をJSONエンコードして表示`, "[]"},
		{"負の末尾(配列)", `A=[0,1,2,3];(Aから{「先頭」:0,「末尾」:-2}を参照)をJSONエンコードして表示`, "[0,1,2]"},
		{"負の先頭(文字列)", `「abc」から{「先頭」:-1,「末尾」:1}を参照して表示`, "ab"},
		{"負の先頭(配列)", `A=[0,1,2,3];(Aから{「先頭」:-1,「末尾」:1}を参照)をJSONエンコードして表示`, "[]"},
		{"末尾が無限大(文字列)", `「abc」から{「先頭」:0,「末尾」:無限大}を参照して表示`, "abc"},
		{"末尾が無限大(配列)", `A=[0,1,2,3];(Aから{「先頭」:0,「末尾」:無限大}を参照)をJSONエンコードして表示`, "[0,1,2,3]"},
		{"末尾がNaN(文字列)", `「abc」から{「先頭」:0,「末尾」:(0÷0)}を参照して表示`, ""},
		{"先頭がNaN(文字列)", `「abc」から{「先頭」:(0÷0),「末尾」:1}を参照して表示`, "ab"},
		{"末尾がNaN(配列)", `A=[0,1,2,3];(Aから{「先頭」:0,「末尾」:(0÷0)}を参照)をJSONエンコードして表示`, "[]"},
		{"日本語", `「あいうえお」から{「先頭」:0,「末尾」:2}を参照して表示`, "あいう"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := run(t, tt.code); got != tt.want {
				t.Errorf("%q = %q, want %q", tt.code, got, tt.want)
			}
		})
	}
}
