// 本家 #2583: 括弧付きの配列要素への代入。期待値は本家 core/test/array_test.mjs と同じ。
func TestParenthesizedArrayAssignment(t *testing.T) {
	for _, target := range []string{"(ホゲ@0)@1", "(ホゲ@0)[1]", "(ホゲ[0])@1", "((ホゲ)@0)@1", "(ホゲ@0@1)"} {
		for _, assign := range []string{
			target + "に72を代入", "72を" + target + "に代入", target + "へ72を代入",
			target + "は72", target + "=72",
		} {
			code := "ホゲは[[1,2],[3,4]]。" + assign + "。ホゲをJSONエンコードして表示。"
			if got := run(t, code); got != "[[1,72],[3,4]]" {
				t.Errorf("%q = %q, want [[1,72],[3,4]]", code, got)
			}
		}
	}
	prefix := "履歴=\"\";●(値を)添字とは\n履歴=履歴&値\n値を戻す\nここまで\nA=[[1,2],[3,4]];"
	tests := []struct{ name, code, want string }{
		{"カンマで次の代入へ", "A=[[1,2]];(A@0)@1=72,B=3;AをJSONエンコードして表示;Bを表示", "[[1,72]]\n3"},
		{"負の添字", "A=[[1,2]];(A@0)@-1=72;(A@0)@-1を表示", "72"},
		{"括弧の計算式", "(1+2)を表示;(1+2)-2を表示", "3\n1"},
		{"括弧の関数呼び出し", "●(値を)二倍とは\n値*2を戻す\nここまで\n(3を二倍)を表示", "6"},
		{"添字の評価順(=)", prefix + "(A@(0を添字))@(1を添字)=72;履歴を表示;AをJSONエンコードして表示", "01\n[[1,72],[3,4]]"},
		{"添字の評価順(代入)", prefix + "(A@(0を添字))@(1を添字)に72を代入;履歴を表示;AをJSONエンコードして表示", "01\n[[1,72],[3,4]]"},
		{"読み取りと比較", "A=[[1,2],[3,4]];(A@0)@1を表示;結果=((A@0)@1=2);結果を表示", "2\ntrue"},
		{"もしの比較", "A=[[1,2]];もし(A@0)@1=2ならば\n「一致」を表示\nここまで", "一致"},
		{"括弧の添字", "A=[10,20,30];B=[1];(A)@(B@0)=72;AをJSONエンコードして表示", "[10,72,30]"},
		{"DNCLの自動初期化(=)", "DNCLモード;(A@0)@1=72;A[0][1]を表示", "72"},
		{"DNCLの自動初期化(代入)", "DNCLモード;(A@0)@1に72を代入;A[0][1]を表示", "72"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := run(t, tt.code); got != tt.want {
				t.Errorf("%q = %q, want %q", tt.code, got, tt.want)
			}
		})
	}
}

// 変数を起点としない括弧付き参照への代入は文法エラーにする (本家 #2583)
func TestParenthesizedArrayAssignmentError(t *testing.T) {
	for _, target := range []string{"([1,2])@0", "(1+2)@0"} {
		for _, code := range []string{target + "=72", target + "に72を代入"} {
			_, err := vm.RunSource(code, "main.nako3", nil)
			var nakoErr *errs.NakoError
			if !errors.As(err, &nakoErr) || nakoErr.Kind != errs.Syntax {
				t.Errorf("%q: err = %v, want 文法エラー", code, err)
			}
		}
	}
}

// 本家 #2590: 文字列の添字アクセス。rune単位で数え、範囲の末尾は含めない。
func TestStringIndex(t *testing.T) {
	tests := []struct{ name, code, want string }{
		{"1文字", "文章=「あいうえお」;文章[0]を表示;文章[1]を表示;文章[-1]を表示;文章@-5を表示", "あ\nい\nお\nあ"},
		{"変数と数字の文字列", "文章=「あいう」;位置=1;文章[位置]を表示;文章[「2」]を表示", "い\nう"},
		{"範囲", "文章=「あいうえお」;文章[0…2]を表示;文章[1...4]を表示;文章[1…-1]を表示;文章[-3…5]を表示", "あい\nいうえ\nいうえ\nうえお"},
		{"範囲の変数", "文章=「あいうえお」;区間=0…2;文章[区間]を表示;文章@(区間)を表示", "あい\nあい"},
		{"範囲の切り詰めと参照命令", "文章=「あいうえお」;文章[-99…99]を表示;文章の0…2を参照して表示", "あいうえお\nあいう"},
		{"範囲外と空の範囲", "文章=「あいう」;結果=[文章[3],文章[-4],文章[2…1],文章[1…1],文章[9…10],(「」)[0],(「」)[0…2]];結果をJSONエンコードして表示", `[null,null,"","","",null,""]`},
		{"絵文字", "文章=「あ😀𠮷い」;文章[1]を表示;文章[2]を表示;文章[-2]を表示;文章[1…3]を表示", "😀\n𠮷\n𠮷\n😀𠮷"},
		{"文字列の変更後", "文章=「あ😀い」;文章[1]を表示;文章[-2]を表示;文章[0…2]を表示;文章=「かきく」;文章[1]を表示;文章[0…2]を表示;文章=「😀𠮷」;文章[1]を表示;文章[-2]を表示;文章[0…2]を表示", "😀\n😀\nあ😀\nき\nかき\n𠮷\n😀\n😀𠮷"},
		{"範囲と同じ構造の辞書", "文章=「あ😀いう」;区間={「先頭」:1,「末尾」:3};文章[区間]を表示", "😀い"},
		{"括弧内の値", "(「あいう」)[0…2]を表示;(「あいう」)@-1を表示", "あい\nう"},
		{"入れ子の要素", "A=[「あいう」];A[0][0…2]を表示;A[0,1]を表示;(A@0)[-1]を表示", "あい\nい\nう"},
		{"関数の戻り値", "●文字列取得とは\n「かきく」を戻す\nここまで\n(文字列取得)[0…2]を表示", "かき"},
		// 『回数』はGo版ではシステム変数なので別の名前で数える
		{"一度だけ評価", "件数=0\n●文字列取得とは\n件数を1増やす\n「abc」を戻す\nここまで\n●位置取得とは\n件数を10増やす\n1を戻す\nここまで\n(文字列取得)[位置取得]を表示\n件数を表示", "b\n11"},
		{"配列と辞書の動作を維持", "A=[1,2];A[-1]=9;A[-1]を表示;A[1]=3;AをJSONエンコードして表示;B={「名前」:「abc」,「-1」:7};B[「名前」][1]を表示;B[-1]を表示;B[「名前」][「length」]を表示", "9\n[1,3]\nb\n7\n3"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := run(t, tt.code); got != tt.want {
				t.Errorf("%q = %q, want %q", tt.code, got, tt.want)
			}
		})
	}
}

// 長い文字列を添字で走査するループが、毎回全文をrune配列にせず終わること (本家 #2590)
func TestStringIndexLongLoop(t *testing.T) {
	for _, units := range [][2]string{{"あ", "い"}, {"😀", "🚀"}} {
		// 長いリテラルは字句解析に時間がかかるため、文字列は実行時に作る
		code := "S=「" + units[0] + "」を100000でリフレイン\nT=「" + units[1] + "」を100000でリフレイン" +
			"\nIで0から99999まで繰り返す:\n    C=S[I]&T[I]\nCを表示"
		if got := run(t, code); got != units[0]+units[1] {
			t.Errorf("got %q, want %q", got, units[0]+units[1])
		}
	}
}

