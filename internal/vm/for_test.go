package vm_test

import "testing"

// Issue #196: 方向指定のない素の『AからBまで繰り返す』は、実行時に from<=to で
// 増方向か減方向かを決める (本家convFor相当)。Go版は常に増方向で emit して
// いたため、from>to のとき一度も実行されなかった。
func TestForDirection(t *testing.T) {
	tests := []struct{ name, code, want string }{
		{"増方向", "5から8まで繰り返す\nそれを表示\nここまで", "5\n6\n7\n8"},
		{"減方向", "10から7まで繰り返す\nそれを表示\nここまで", "10\n9\n8\n7"},
		{"同値は1回", "3から3まで繰り返す\nそれを表示\nここまで", "3"},
		{"減方向-ループ変数", "Iを5から2まで繰り返す\nIを表示\nここまで", "5\n4\n3\n2"},
		{"式で決まる向き", "A=2\n1からAまで繰り返す\nそれを表示\nここまで", "1\n2"},
		{"範囲オブジェクト減方向", "5から2の範囲を繰り返す\nそれを表示\nここまで", "5\n4\n3\n2"},
		{"増繰返は増のみ", "5から3まで増繰り返す\nそれを表示\nここまで", ""},
		{"減繰返は減のみ", "3から5まで減繰り返す\nそれを表示\nここまで", ""},
		{"減繰返実行", "5から3まで減繰り返す\nそれを表示\nここまで", "5\n4\n3"},
		{"増繰返実行", "3から5まで増繰り返す\nそれを表示\nここまで", "3\n4\n5"},
		{"ずつ増やして", "1から5まで2ずつ増やして繰り返す\nそれを表示\nここまで", "1\n3\n5"},
		{"ずつ減らして", "7から1まで2ずつ減らして繰り返す\nそれを表示\nここまで", "7\n5\n3\n1"},
		{"抜ける併用", "10から1まで繰り返す\nもしそれ=8ならば抜ける\nそれを表示\nここまで", "10\n9"},
		{"続ける併用", "3から1まで繰り返す\nもしそれ=2ならば続ける\nそれを表示\nここまで", "3\n1"},
		// 向きを実行時に決めるため本体は1回だけemitする。2回emitしていた
		// 頃の回帰 (本体内の定数宣言が「既に定義済み」でコンパイル不能) を防ぐ。
		{"本体内の定数宣言", "3から3まで繰り返す\n定数のA=5\nAを表示\nここまで", "5"},
		{"本体内の定数宣言-減", "3から1まで繰り返す\nもしそれ=2ならば抜ける\n定数のA=5\nAを表示\nここまで", "5"},
		{"同値-増繰返", "3から3まで増繰り返す\nそれを表示\nここまで", "3"},
		{"同値-減繰返", "3から3まで減繰り返す\nそれを表示\nここまで", "3"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := run(t, tt.code); got != tt.want {
				t.Errorf("%q = %q, want %q", tt.code, got, tt.want)
			}
		})
	}
}
